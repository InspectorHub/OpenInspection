#!/usr/bin/env node
/**
 * Regenerate tests/web-isolation.json, the list of web specs that run in the shared vitest projects
 * (`web-node-shared` and `web-dom-shared`, both isolate: false).
 *
 *   node scripts/gen-web-isolation.mjs          write the manifest
 *   node scripts/gen-web-isolation.mjs --check  print the counts, write nothing
 *
 * `shared.node` and `shared.dom` hold every spec the rules in scripts/lib/web-isolation.mjs accept,
 * split by the environment the spec declares, minus `forcedIsolated`: specs that pass the static
 * rules but were measured to fail or flake when sharing a registry. Each entry there carries its
 * reason and is preserved across regeneration. Move a spec there when a shared run shows it
 * failing, never the other way round without a repeated shared run.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { listWebSpecs, webSharedProblems } from './lib/web-isolation.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = join(ROOT, 'tests/web-isolation.json');

const forced = existsSync(MANIFEST) ? (JSON.parse(readFileSync(MANIFEST, 'utf8')).forcedIsolated ?? {}) : {};
const specs = listWebSpecs(ROOT);
const cache = new Map();
const shared = { node: [], dom: [] };
const rejected = {};
for (const s of specs) {
    if (forced[s]) continue;
    const { env, problems } = webSharedProblems(ROOT, s, cache);
    if (problems.length === 0) (env === 'happy-dom' ? shared.dom : shared.node).push(s);
    else {
        for (const p of new Set(problems.map((x) => x.replace(/^helper [^:]+: /, 'helper: ').replace(/^(server|app|packages)\/\S+: /, 'module state: ')))) {
            rejected[p] = (rejected[p] ?? 0) + 1;
        }
    }
}
const total = shared.node.length + shared.dom.length;
console.log(`specs ${specs.length}  shared ${total} (node ${shared.node.length}, dom ${shared.dom.length})  isolated ${specs.length - total} (forced ${Object.keys(forced).length})`);
console.log('rejections by reason (a spec can have several):', rejected);
if (shared.node.length === 0 || shared.dom.length === 0) {
    console.error('Refusing to write an empty shared list.');
    process.exit(1);
}
if (!process.argv.includes('--check')) {
    const doc = {
        _comment:
            'Generated by scripts/gen-web-isolation.mjs. `shared.node` runs in vitest project web-node-shared and `shared.dom` in web-dom-shared (both isolate:false); everything else in web-isolated. forcedIsolated = passes the static rules but failed or flaked when shared, with the reason.',
        forcedIsolated: forced,
        shared,
    };
    writeFileSync(MANIFEST, JSON.stringify(doc, null, 2) + '\n');
}
