#!/usr/bin/env node
/**
 * check-loader-awaits.mjs — a ratchet on SEQUENTIAL awaits at the top level of
 * a route module.
 *
 * WHAT WENT WRONG, ONCE. The inspection loader awaited fifteen in-process API
 * calls one at a time. Measured 2026-09-07 by timestamping every D1 statement
 * of a real render: only two of the fifteen overlapped, and the other thirteen
 * ran strictly single file — report-translation 70-78ms, consent 79-89, me
 * 91-97, people 98-106, and so on to statutory-form at 153-156. About 86ms of
 * the render's 156ms of database time was spent waiting for the call before.
 * Restructured into two waves, the render's round-trip DEPTH fell from 32 to 5.
 *
 * DEPTH, NOT COUNT, is what a remote D1 charges for: each sequential await is a
 * network round trip the page waits out before starting the next. Running the
 * same statements concurrently costs the same statements and a fraction of the
 * latency.
 *
 * That regression is invisible in review — a fifteenth `await api.x` looks
 * exactly like the fourteenth above it — and it cannot be caught by a type, a
 * test, or eslint's own rules. So it is counted.
 *
 * ── WHAT THIS COUNTS, AND WHAT IT CANNOT ────────────────────────────────────
 * A statement indented exactly two spaces in a route module is at the top level
 * of its function, because eslint enforces the indent here. Anything nested —
 * inside an `if`, a callback, or an async IIFE later collected into a
 * `Promise.all` — is indented deeper and is NOT counted. `await Promise.all(`
 * is excluded outright: that IS the batched form this gate exists to encourage.
 *
 * ⚠️ So this is a PROXY for "how many round trips does this loader take in
 * sequence", not a measurement of it. A loader can still serialise work in ways
 * a line-shape cannot see, and a file can hold several functions. The claim
 * being made is narrower: the number moves when someone adds a sequential
 * await, which is the drift that actually happened. Do not quote it as a
 * round-trip count.
 *
 * Prints measured AND baseline every run. Scanning zero files is a FAILURE, not
 * a pass — an empty result set reads as green, which is how a dead instrument
 * hides.
 *
 * USAGE
 *   node scripts/check-loader-awaits.mjs            # check against baseline
 *   node scripts/check-loader-awaits.mjs --update   # regenerate baseline
 */
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { dirname, join, resolve, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");
const BASELINE_PATH = join(HERE, "loader-awaits-baseline.json");
const BASELINE_REL = "scripts/loader-awaits-baseline.json";
const SCAN_DIR = "app/routes";
const UPDATE = process.argv.includes("--update");

/** Repo-relative POSIX path, so baseline keys match on Windows and on CI. */
const rel = (abs) => relative(ROOT, abs).split("\\").join("/");

const failures = [];
const hints = [];

function walk(absDir, out = []) {
  for (const entry of readdirSync(absDir)) {
    const abs = join(absDir, entry);
    if (statSync(abs).isDirectory()) {
      if (entry === "node_modules") continue;
      walk(abs, out);
      continue;
    }
    if (!/\.tsx?$/.test(entry)) continue;
    if (/\.(test|spec)\./.test(entry)) continue;
    out.push(abs);
  }
  return out;
}

const scanAbs = join(ROOT, SCAN_DIR);
if (!existsSync(scanAbs)) {
  console.error(`  ✗  ${SCAN_DIR}/ does not exist — this gate has nothing to scan.`);
  process.exit(1);
}

const files = walk(scanAbs);
const map = {};
let total = 0;
for (const abs of files) {
  let n = 0;
  for (const line of readFileSync(abs, "utf8").split(/\r?\n/)) {
    if (!/^ {2}(?:const .*?= )?await /.test(line)) continue;
    if (/await Promise\.all\(/.test(line)) continue;
    n += 1;
  }
  if (n > 0) {
    map[rel(abs)] = n;
    total += n;
  }
}

// Scanning nothing is a broken walker, not a clean repo.
if (files.length === 0) failures.push(`${SCAN_DIR}/: scanned ZERO route files — the walker is broken.`);
if (Object.keys(map).length === 0) {
  failures.push(`${SCAN_DIR}/: found ZERO top-level awaits across ${files.length} files — the matcher is broken; loaders do await.`);
}

if (UPDATE) {
  if (failures.length > 0) {
    console.error("Refusing to write a baseline from a broken instrument:\n");
    for (const f of failures) console.error(`       ${f}`);
    process.exit(1);
  }
  writeFileSync(
    BASELINE_PATH,
    `${JSON.stringify(
      {
        $comment: [
          "Generated by scripts/check-loader-awaits.mjs --update. Do not hand-edit.",
          "Counts sequential top-level awaits per route module. A PROXY for round-trip depth, not a measurement of it.",
          "Growth means someone added an await that waits on the one before it. If it does not depend on it, batch it.",
        ],
        total,
        files: Object.fromEntries(Object.entries(map).sort(([a], [b]) => (a < b ? -1 : 1))),
      },
      null,
      2,
    )}\n`,
    "utf8",
  );
  console.log(`  ✓  baseline updated: ${total} sequential await(s) across ${Object.keys(map).length} file(s)`);
  process.exit(0);
}

if (!existsSync(BASELINE_PATH)) {
  console.error(`  ✗  no baseline at ${BASELINE_REL}. Run: node scripts/check-loader-awaits.mjs --update`);
  process.exit(1);
}

const baseline = JSON.parse(readFileSync(BASELINE_PATH, "utf8"));
const baseFiles = baseline.files ?? {};

console.log(`  loader sequential awaits: measured ${total}  baseline ${baseline.total ?? 0}`);
console.log(`  scanned ${files.length} route file(s), ${Object.keys(map).length} with top-level awaits`);

let grown = 0;
let shrank = 0;
for (const [file, n] of Object.entries(map).sort(([a], [b]) => (a < b ? -1 : 1))) {
  const b = baseFiles[file];
  if (b === undefined) {
    failures.push(
      `${file}: ${n} sequential top-level await(s), and this file is not in the baseline. ` +
        `Each one is a round trip the page waits out before starting the next. If they do not ` +
        `depend on each other, collect them into a Promise.all; if they genuinely do, re-baseline ` +
        `with --update and say which depends on which.`,
    );
    continue;
  }
  if (n > b) {
    grown += 1;
    console.log(`    GROWTH ${file}: ${n} (baseline ${b})`);
    failures.push(
      `${file}: sequential top-level awaits grew ${b} -> ${n}. The inspection loader once had ` +
        `fifteen of these and spent 86ms of a 156ms render waiting on them in turn. If the new ` +
        `read does not depend on the one before it, put it in the wave; otherwise re-baseline ` +
        `with --update and say what it depends on.`,
    );
  } else if (n < b) {
    shrank += 1;
  }
}
if (shrank > 0) hints.push(`${shrank} file(s) fell below baseline — run --update to tighten the ratchet.`);
if (grown === 0) console.log("    no per-file growth");

for (const h of hints) console.log(`  HINT  ${h}`);

if (failures.length > 0) {
  console.error(`\n  ✗  loader await budget: ${failures.length} problem(s)`);
  for (const f of failures) console.error(`       ${f}`);
  process.exit(1);
}
console.log("  ✓  loader await budget within baseline");
