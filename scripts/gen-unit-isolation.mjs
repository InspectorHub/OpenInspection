#!/usr/bin/env node
/**
 * Regenerate tests/unit/isolation.json, the list of api unit specs that run in
 * the `api-shared` vitest project (isolate: false).
 *
 *   node scripts/gen-unit-isolation.mjs          write the manifest
 *   node scripts/gen-unit-isolation.mjs --check  print the counts, write nothing
 *
 * `shared` is every spec the rules in scripts/lib/unit-isolation.mjs accept,
 * minus `forcedIsolated`: specs that pass the static rules but were measured to
 * fail or flake when sharing a registry. Each entry there carries its reason and
 * is preserved across regeneration. Move a spec there when a shared run shows it
 * failing, never the other way round without a repeated shared run.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sharedProblems } from './lib/unit-isolation.mjs';
import { listSpecs } from './lib/list-unit-specs.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = join(ROOT, 'tests/unit/isolation.json');

const forced = existsSync(MANIFEST) ? JSON.parse(readFileSync(MANIFEST, 'utf8')).forcedIsolated ?? {} : {};
const specs = listSpecs(ROOT);
const cache = new Map();
const shared = [];
const rejected = {};
for (const s of specs) {
    if (forced[s]) continue;
    const problems = sharedProblems(ROOT, s, cache);
    if (problems.length === 0) shared.push(s);
    else for (const p of new Set(problems.map((x) => x.replace(/^helper [^:]+: /, 'helper: ').replace(/^(server|app|packages)\/\S+: /, 'module state: ')))) rejected[p] = (rejected[p] ?? 0) + 1;
}
console.log(`specs ${specs.length}  shared ${shared.length}  isolated ${specs.length - shared.length} (forced ${Object.keys(forced).length})`);
console.log('rejections by reason (a spec can have several):', rejected);
if (shared.length === 0) {
    console.error('Refusing to write an empty shared list.');
    process.exit(1);
}
if (!process.argv.includes('--check')) {
    const doc = {
        _comment: 'Generated by scripts/gen-unit-isolation.mjs. `shared` runs in vitest project api-shared (isolate:false); everything else in api-isolated. forcedIsolated = passes the static rules but failed or flaked when shared, with the reason.',
        forcedIsolated: forced,
        shared,
    };
    writeFileSync(MANIFEST, JSON.stringify(doc, null, 2) + '\n');
}
