export function configurationScope({ vars, tenantConfigured = false, tenantOwned = false, integrationSecret = false, splitIntegration = false }) {
    if (tenantConfigured) return 'Tenant setting (request-injected)';
    if (splitIntegration) return 'Tenant key for BYO inbound/status; deployment binding for managed compliance webhook';
    if (tenantOwned) return 'Tenant setting takes precedence over deployment default';
    if (integrationSecret) return 'Deployment default and tenant fallback (request-injected)';
    if (vars) return 'Deployment configuration';
    return 'Deployment binding or Worker context';
}

export function renderEnvironmentDoc({ vars, properties }) {
    const entries = new Map();
    for (const [name] of Object.entries(vars)) entries.set(name, { name, optional: true, source: 'Wrangler variable', scope: configurationScope({ vars: true }) });
    for (const property of properties) entries.set(property.name, {
        name: property.name,
        optional: property.optional,
        source: vars[property.name] === undefined ? 'Worker environment type' : 'Wrangler variable and Worker environment type',
        scope: property.scope ?? configurationScope({ vars: vars[property.name] !== undefined }),
    });
    const rows = [...entries.values()].sort((a, b) => a.name.localeCompare(b.name)).map(({ name, optional, source, scope }) =>
        `| \`${name}\` | ${optional ? 'Optional' : 'Required'} | ${source} | ${scope} |`);
    return [
        '# Environment variables and bindings',
        '',
        '<!-- GENERATED by scripts/gen-env-doc.mjs. Edit wrangler.jsonc, Worker environment types, the integration-secret catalog, or tenant-owned precedence policy, then run `npm run docs:env`. -->',
        '',
        'This reference lists names declared by the committed Wrangler configuration and the Worker request context types. A Worker type can also describe a value injected from tenant settings at request time; the configuration scope column distinguishes those from deployment configuration. Secret values are never included.',
        '',
        '| Name | Type status | Declaration source | Configuration scope |',
        '|---|---|---|---|',
        ...rows,
        '',
    ].join('\n');
}

export function compareGenerated(current, generated) {
    return current.replace(/\r\n/g, '\n') === generated.replace(/\r\n/g, '\n');
}

export function missingEnvironmentNames(current, generated) {
    const readNames = (text) => new Set([...text.matchAll(/^\|\s*`([A-Z][A-Z0-9_]*)`\s*\|/gm)].map((match) => match[1]));
    const currentNames = readNames(current);
    return [...readNames(generated)].filter((name) => !currentNames.has(name));
}
